// where the sequence starts once the stage pins: the first name is already entering the view at the bottom
const START = 0.45
/** View heights of scroll the whole sequence takes once the stage pins. */
export const PICTURE_TRAIL_LENGTH = 5 - START

const DISPLAY = "font-heading text-[length:min(calc(var(--story-u)*23),25cqh)] leading-none font-normal tracking-[-0.03em] whitespace-nowrap max-[900px]:text-[length:calc(var(--story-u)*5.6)]"
const H2 = "font-heading text-[length:calc(var(--story-u)*6)] leading-[1.2] font-normal tracking-[-0.02em] max-[900px]:text-[length:calc(var(--story-u)*2.8)] max-[900px]:leading-none"
// every moving part sits at the stage's top left and is moved by translate + scale
const PART = "invisible absolute top-0 left-0 origin-center will-change-transform"

/** The layout for a box: a wide one from 900px across, else a tablet, or a phone below an aspect of 13 : 20. */
export function layoutFor(width: number, height: number): PictureTrailLayout {
  if (width >= 900) return "desktop"
  return width / Math.max(1, height) >= 13 / 20 ? "tablet" : "phone"
}

/** A track's values at `v` view heights after the stage pins, linearly between keys and held past either end:
 * [centre x, centre y, scale, opacity] into out. */
export function trackAt(track: Track, v: number, out: number[]) {
  const keys = track.keys
  let a = keys[0]!
  let b = a
  if (v >= keys[keys.length - 1]![0]!) a = b = keys[keys.length - 1]!
  else if (v > a[0]!) {
    let lo = 0
    let hi = keys.length - 1
    while (hi - lo > 1) {
      const m = (lo + hi) >> 1
      if (keys[m]![0]! <= v) lo = m
      else hi = m
    }
    a = keys[lo]!
    b = keys[hi]!
  }
  const f = b[0]! > a[0]! ? (v - a[0]!) / (b[0]! - a[0]!) : 0
  for (let c = 1; c <= 4; c++) {
    const from = a[c] ?? 1
    out[c - 1] = from + ((b[c] ?? 1) - from) * f
  }
  return out
}

/** Whether a timed part is on at `v` (inside one of its windows). */
export const isOn = (track: Track, v: number) => (track.on ?? []).some(([from, to]) => v >= from && v < to)

/** The nearest ancestor that scrolls vertically, or null when the page itself does. */
function scrollParent(node: HTMLElement): HTMLElement | null {
  for (let el = node.parentElement; el && el !== document.body && el !== document.documentElement; el = el.parentElement) {
    const { overflowY } = getComputedStyle(el)
    if (overflowY === "auto" || overflowY === "scroll") return el
  }
  return null
}

/**
 * A picture's trail through time, told as the reader scrolls on a pinned stage: a huge name crosses the view, the
 * holders pass in turn beside the picture, and a second huge name follows and stays faded behind it. Pins to its
 * nearest scroll container, or to the page. Only transform and opacity change as it scrolls; with reduced motion
 * it rests at its end.
 */
export function PictureTrail({
  top = "Conqueror",
  bottom = "Last ruler",
  holders = ["First dynasty", "Second dynasty", "Third dynasty", "Fourth dynasty", "Fifth dynasty", "Sixth dynasty"],
  image = {
    src: "https://picsum.photos/seed/mewo-picture-trail-1/1330/1478",
    credit: { title: "The siege", by: "c. 1258 CE", line: "A museum somewhere. Placeholder photograph.", href: "#" },
  },
  className,
  style,
  ...props
}: PictureTrailProps) {
  const stageRef = React.useRef<HTMLDivElement>(null)

  React.useEffect(() => {
    const stage = stageRef.current
    // The root's ref stays the consumer's, so the section is reached through the stage.
    const section = stage?.parentElement
    if (!stage || !section) return
    const scroller = scrollParent(section)
    const reduced = window.matchMedia?.("(prefers-reduced-motion: reduce)").matches ?? false
    const parts = [...stage.querySelectorAll<HTMLElement>("[data-part]")]
    const out = [0, 0, 1, 1]
    type Bound = { el: HTMLElement; part: Part; w: number; h: number; y: number; h2: number; last: string }
    let bound: Bound[] = []
    let layout: PictureTrailLayout = "desktop"
    let width = 1
    let height = 1
    let near = true
    let raf = 0

    const measure = () => {
      // Inside a scroll container the stage pins to that container, not the window.
      if (scroller) section.style.setProperty("--mewo-viewport", `${scroller.clientHeight}px`)
      width = Math.max(1, stage.clientWidth)
      height = Math.max(1, stage.clientHeight)
      layout = layoutFor(width, height)
      bound = parts.map((el) => ({ el, part: el.dataset.part as Part, w: el.offsetWidth, h: el.offsetHeight, y: 0, h2: 0, last: "" }))
    }
    const update = () => {
      raf = 0
      const viewport = scroller ? scroller.clientHeight : window.innerHeight
      const top = section.getBoundingClientRect().top - (scroller ? scroller.getBoundingClientRect().top : 0)
      const v = START + (reduced ? PICTURE_TRAIL_LENGTH : -top / Math.max(1, viewport))
      const set = TRACKS[layout]
      const vw = width / 100
      const vh = height / 100
      let picture: Bound | undefined
      for (const b of bound) {
        const track = set[b.part]
        if (!track) continue
        if (track.on) {
          // a timed part sits still and fades by its windows
          const on = isOn(track, v)
          if (on !== b.el.hasAttribute("data-on")) b.el.toggleAttribute("data-on", on)
        }
        const [cx, cy, s, o] = trackAt(track, v, out) as [number, number, number, number]
        const x = cx * vw - b.w / 2
        let y = cy * vh - b.h / 2
        // the credit hangs under the picture, whatever the box's shape
        if (b.part === "credit" && picture) y = picture.y + (picture.h * (1 + picture.h2)) / 2 + vh
        if (b.part === "img") {
          picture = b
          b.y = y
          b.h2 = s
        }
        const key = `${x.toFixed(1)}|${y.toFixed(1)}|${s.toFixed(4)}|${o.toFixed(3)}`
        if (key === b.last) continue
        b.last = key
        // position through translate, so a CSS scale on the part (the timed line's entrance) scales it about its centre
        b.el.style.translate = `${x.toFixed(2)}px ${y.toFixed(2)}px`
        b.el.style.transform = `scale(${s.toFixed(4)})`
        if (track.on) continue
        b.el.style.opacity = o.toFixed(3)
        b.el.style.visibility = o < 0.002 ? "hidden" : "visible"
      }
    }
    const schedule = () => {
      if (!raf && near) raf = requestAnimationFrame(update)
    }
    const remeasure = () => {
      measure()
      schedule()
    }

    measure()
    schedule()
    const resizeObserver = new ResizeObserver(remeasure)
    resizeObserver.observe(stage)
    if (scroller) resizeObserver.observe(scroller)
    document.fonts?.ready.then(remeasure)
    // far from view it doesn't measure on every scroll (against the window, so a scroll box leaving the page counts)
    const intersection = new IntersectionObserver(
      (entries) => {
        near = entries.some((entry) => entry.isIntersecting)
        if (near) {
          for (const b of bound) b.last = ""
          schedule()
        }
      },
      { rootMargin: "50% 0px" }
    )
    intersection.observe(section)
    const target = scroller ?? window
    target.addEventListener("scroll", schedule, { passive: true })
    return () => {
      cancelAnimationFrame(raf)
      resizeObserver.disconnect()
      intersection.disconnect()
      target.removeEventListener("scroll", schedule)
    }
  }, [holders.length])

  const alt = image.alt ?? `${image.credit.title}, ${image.credit.by}`
  return (
    <section
      data-slot="picture-trail"
      className={cn(
        "[--story-u:min(2.6667cqw,12px)] min-[901px]:[--story-u:0.625cqw] text-[length:var(--story-u)]",
        "relative h-[calc(var(--mewo-viewport,100vh)*var(--mewo-length))]",
        className
      )}
      style={{ "--mewo-length": PICTURE_TRAIL_LENGTH + 1, ...style } as React.CSSProperties}
      {...props}
    >
      <div ref={stageRef} data-slot="picture-trail-stage" className="sticky top-0 h-[var(--mewo-viewport,100vh)] w-full overflow-hidden [container-type:size]">
        <p data-part="top" className={cn(PART, DISPLAY)}>
          {top}
        </p>
        <p data-part="bottom" className={cn(PART, DISPLAY)}>
          {bottom}
        </p>
        {holders.slice(0, 6).map((h, i) => (
          <p
            key={i}
            data-part={`buyer${i}`}
            className={cn(
              PART,
              "w-[calc(var(--story-u)*45)] max-w-full max-[900px]:w-[calc(100cqw-calc(var(--story-u)*2))] max-[900px]:text-center max-[900px]:text-[length:calc(var(--story-u)*2.4)] max-[900px]:leading-none max-[900px]:whitespace-nowrap",
              H2
            )}
          >
            {h}
          </p>
        ))}
        <div data-part="img" className={cn(PART, "aspect-[2000/2215] w-[100cqw] max-[900px]:h-[130cqh] max-[900px]:w-auto")}>
          {/* eslint-disable-next-line @next/next/no-img-element -- items cannot use next/image */}
          <img src={image.src} alt={alt} decoding="async" className="absolute inset-0 size-full object-cover" />
        </div>
        <p data-part="credit" className={cn(PART, "grid w-[calc(var(--story-u)*19.8)] gap-[calc(var(--story-u)*0.5)] text-center max-[900px]:w-[calc(var(--story-u)*15)]")}>
          <span className="text-[length:max(12px,calc(var(--story-u)*1.2))] leading-[1.2] max-[900px]:text-[length:calc(var(--story-u)*1)]">
            <a href={image.credit.href} target="_blank" rel="noopener noreferrer" className="pointer-events-auto">
              <em className="not-italic underline underline-offset-[0.15em]">{image.credit.title}</em>
            </a>
            , {image.credit.by}
          </span>
          <span className="text-[10px] leading-[1.25] text-muted-foreground">{image.credit.line}</span>
        </p>
      </div>
    </section>
  )
}
